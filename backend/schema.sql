-- Junction table per the ERD's Relationship Matrix: one arrest/surrender
-- event can link multiple accused. (Note: ArrestSurrender also carries a
-- direct AccusedMasterID column above — both are kept exactly as specified
-- in the source ERD, which documents this junction independently.)
CREATE TABLE IF NOT EXISTS inv_arrestsurrenderaccused (
  ArrestSurrenderID INT NOT NULL,
  AccusedMasterID   INT NOT NULL,
  PRIMARY KEY (ArrestSurrenderID, AccusedMasterID),
  FOREIGN KEY (ArrestSurrenderID) REFERENCES ArrestSurrender (ArrestSurrenderID),
  FOREIGN KEY (AccusedMasterID)   REFERENCES Accused (AccusedMasterID)
);

CREATE TABLE IF NOT EXISTS ChargesheetDetails (
  CSID           INT      NOT NULL,
  CaseMasterID   INT      NOT NULL,
  csdate         DATETIME,
  cstype         CHAR(1),                   -- A=Chargesheet, B=False Case, C=Undetected
  PolicePersonID INT,
  PRIMARY KEY (CSID),
  FOREIGN KEY (CaseMasterID)   REFERENCES CaseMaster (CaseMasterID),
  FOREIGN KEY (PolicePersonID) REFERENCES Employee (EmployeeID)
);
CREATE INDEX idx_chargesheet_case ON ChargesheetDetails (CaseMasterID);


-- ═══════════════════════════════════════════════════════════════════════════
-- SECTION 2 — APPLICATION EXTENSION TABLES (not part of the supplied ERD)
-- Each exists to satisfy an explicit hackathon capability the base FIR
-- registry does not model. Kept separate from Section 1 by design.
-- ═══════════════════════════════════════════════════════════════════════════

-- Extension reason: app login + role-based access control (Module 13 /
-- "Secure Role-Based Access & Governance"). The ERD's Employee table has no
-- concept of an application role or login credential.
CREATE TABLE IF NOT EXISTS UserProfiles (
  user_id      VARCHAR(50)  NOT NULL,
  email        VARCHAR(100) NOT NULL,
  first_name   VARCHAR(50)  NOT NULL,
  last_name    VARCHAR(50)  NOT NULL,
  role         VARCHAR(30)  NOT NULL,   -- admin|supervisor|investigator|analyst|policymaker
  EmployeeID   INT,                     -- optional link to Employee if the user is a serving officer
  is_active    TINYINT(1)   DEFAULT 1,
  created_at   DATETIME     DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id),
  FOREIGN KEY (EmployeeID) REFERENCES Employee (EmployeeID)
);

-- Extension reason: audit trail / accountability (Module 13). No table in
-- the ERD records who queried or exported what.
CREATE TABLE IF NOT EXISTS AuditLogs (
  log_id        VARCHAR(30) NOT NULL,
  user_id       VARCHAR(50),
  action        VARCHAR(80),
  resource_type VARCHAR(40),
  resource_id   VARCHAR(40),
  query_text    TEXT,
  ip_address    VARCHAR(45),
  created_at    DATETIME    DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (log_id),
  FOREIGN KEY (user_id) REFERENCES UserProfiles (user_id)
);

-- Extension reason: "Criminal Network & Relationship Analysis" is an
-- explicit required capability, but the ERD has no graph/edge concept
-- linking accused, victims, locations, or accounts across cases.
CREATE TABLE IF NOT EXISTS Relationships (
  rel_id    VARCHAR(20) NOT NULL,
  from_id   VARCHAR(20) NOT NULL,       -- e.g. AccusedMasterID, VictimMasterID
  from_type VARCHAR(20),                -- Accused|Victim|Employee|Account
  to_id     VARCHAR(20) NOT NULL,
  to_type   VARCHAR(20),
  rel_type  VARCHAR(60),                -- Co-offender|Gang Member|Associate|Financial Link
  strength  DECIMAL(4,2),               -- 0.0–1.0 confidence
  CaseMasterID INT,                     -- evidencing case, if any
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (rel_id),
  FOREIGN KEY (CaseMasterID) REFERENCES CaseMaster (CaseMasterID)
);
CREATE INDEX idx_rel_from ON Relationships (from_id, from_type);
CREATE INDEX idx_rel_to   ON Relationships (to_id, to_type);

-- Extension reason: "Financial Crime & Transaction Link Analysis" is an
-- explicit required capability; the ERD has no financial-account concept.
CREATE TABLE IF NOT EXISTS FinancialAccounts (
  account_id              VARCHAR(20)  NOT NULL,
  account_number          VARCHAR(50),
  bank                    VARCHAR(80),
  linked_accused_id       INT,                    -- FK -> Accused.AccusedMasterID
  flagged                 TINYINT(1)   DEFAULT 0,
  suspicious_txn_count    INT          DEFAULT 0,
  total_suspicious_amount BIGINT       DEFAULT 0,
  notes                   TEXT,
  created_at              DATETIME     DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (account_id),
  FOREIGN KEY (linked_accused_id) REFERENCES Accused (AccusedMasterID)
);
CREATE INDEX idx_finacc_accused ON FinancialAccounts (linked_accused_id);
CREATE INDEX idx_finacc_flagged ON FinancialAccounts (flagged);

-- ═══════════════════════════════════════════════════════════════════════════
-- SECTION 3 — CHAT & BRIEFING HISTORY (persisted server-side, not localStorage)
-- Every officer's chat conversations and generated intelligence briefings are
-- stored here so they survive across devices/sessions and can be revisited
-- or deleted — matching how consumer AI assistants persist conversation
-- history server-side rather than only in browser storage.
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS ChatSessions (
  session_id     VARCHAR(40)  NOT NULL,
  user_id        VARCHAR(50)  NOT NULL,
  title          VARCHAR(200),          -- RAG-rephrased short title from the first question
  message_count  INT          DEFAULT 0,
  created_at     DATETIME     DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME     DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (session_id),
  FOREIGN KEY (user_id) REFERENCES UserProfiles (user_id)
);
CREATE INDEX idx_chatsess_user ON ChatSessions (user_id, updated_at);

CREATE TABLE IF NOT EXISTS ChatMessages (
  message_id   VARCHAR(40) NOT NULL,
  session_id   VARCHAR(40) NOT NULL,
  sender       VARCHAR(10) NOT NULL,    -- user|ai
  text         TEXT,
  intent       VARCHAR(40),
  confidence   INT,
  reasoning    TEXT,                    -- JSON-encoded string[]
  highlights   TEXT,                    -- JSON-encoded array
  suggestions  TEXT,                    -- JSON-encoded string[]
  action       TEXT,                    -- JSON-encoded object|null
  alert        TEXT,
  evidence     TEXT,                    -- JSON-encoded string[]
  created_at   DATETIME    DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (message_id),
  FOREIGN KEY (session_id) REFERENCES ChatSessions (session_id)
);
CREATE INDEX idx_chatmsg_session ON ChatMessages (session_id, created_at);

CREATE TABLE IF NOT EXISTS Briefings (
  briefing_id   VARCHAR(40) NOT NULL,
  user_id       VARCHAR(50) NOT NULL,
  scope         VARCHAR(100),
  generated_by  VARCHAR(20),            -- rag|template
  confidence    INT,
  briefing_text TEXT,
  stats         TEXT,                   -- JSON-encoded snapshot
  created_at    DATETIME    DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (briefing_id),
  FOREIGN KEY (user_id) REFERENCES UserProfiles (user_id)
);
CREATE INDEX idx_briefing_user ON Briefings (user_id, created_at);

-- Extension reason: the ERD has no photograph/image concept for Accused at
-- all. Real photos aren't available in this dataset, so the UI shows a
-- default silhouette poster and lets an officer attach one manually — stored
-- as a resized/compressed base64 JPEG data URI.
--
-- CHUNKED BY DESIGN: Catalyst's Data Store silently truncates any TEXT
-- column value to exactly 10,000 characters (confirmed empirically — not
-- documented) rather than erroring, which corrupted every photo above ~7KB
-- raw into an unparseable data URI. A single ~15-40KB compressed thumbnail
-- doesn't fit in one TEXT cell, so it's split into <=8000-char chunks across
-- multiple rows here and reassembled by chunk_index on read.
CREATE TABLE IF NOT EXISTS AccusedPhotoChunks (
  chunk_id     VARCHAR(40) NOT NULL,   -- '<accused_id>-<chunk_index>', e.g. 'ACC-123-0'
  accused_id   VARCHAR(20) NOT NULL,   -- e.g. 'ACC-123' — the app's display ID
  chunk_index  INT         NOT NULL,
  chunk_data   TEXT,                   -- <=8000 chars of the base64 data URI, well under the 10,000 cap
  uploaded_by  VARCHAR(50),
  uploaded_at  DATETIME    DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (chunk_id)
);
CREATE INDEX idx_photochunk_accused ON AccusedPhotoChunks (accused_id, chunk_index);
